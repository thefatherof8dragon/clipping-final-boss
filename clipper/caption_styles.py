def get_caption_style(style_id: str) -> Dict[str, Any]:
    """Retrieve caption style by ID with fallback to 'pop'."""
    clean_id = (style_id or "pop").lower().strip()
    return CAPTION_TEMPLATES.get(clean_id, CAPTION_TEMPLATES["pop"])

def list_caption_styles() -> List[Dict[str, Any]]:
    """Return list of all 10 visual template definitions."""
    return list(CAPTION_TEMPLATES.values())
